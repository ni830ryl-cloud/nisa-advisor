"""Layer 0: 免責同意画面"""

import streamlit as st


def render() -> None:
    """免責事項を表示しユーザーの同意を取得する"""
    st.title("📊 NISA成長投資枠 ファンド推奨ツール")
    st.subheader("ご利用にあたって（必ずお読みください）")

    st.markdown("""
本ツールは投資の参考情報を提供するスクリーニング支援ツールであり、
**投資助言業務を行うものではありません**。

---

### ⚠️ 重要事項

- 本ツールが提示するファンドは「**推奨**」ではなく、
  入力情報に基づくスコアリング結果と判断材料です
- **最終的な投資判断は、ご自身の責任で行ってください**
- 過去のリターンは将来の運用成果を保証するものではありません
- ファンド情報の正確性・最新性を保証するものではありません
- 入力された情報はサーバーに保存されません

---

### 本ツールができないこと

- 個別の財務状況・税制を考慮したアドバイス
- 特定銘柄の売買タイミングの判断
- 将来の市場予測

---

### 推奨される使い方

- スクリーニングの第一段階として利用
- 出力結果を出発点に、ご自身で詳細を調査
- 必要に応じて、有資格のファイナンシャルアドバイザーに相談

---
    """)

    agree = st.checkbox("上記内容を理解し、同意します")

    if st.button("同意して次へ進む", disabled=not agree, type="primary"):
        st.session_state.consent = True
        st.session_state.current_page = "profiling"
        st.rerun()
